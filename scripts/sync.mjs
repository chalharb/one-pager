#!/usr/bin/env node
// Copy the shared files into every skill, so each skill folder works on its own
// when installed alone (the skills CLI and ChatGPT copy one folder per skill).
//
//   node scripts/sync.mjs          # write the copies
//   node scripts/sync.mjs --check  # exit 1 if any copy is out of date (CI)
//
// Edit files in shared/, never the copies in .agents/skills/<skill>/.
//   - shared/snippets/INDEX.md is generated from the header comment at the top
//     of every snippet file, plus shared/snippets/choosing.md.
//   - Every other file in shared/ is copied as is, except style.css and
//     choosing.md, which are inputs only.
//   - shared/style.css is spliced into each skill's template.html and
//     examples/*.html between the @shared-css markers.
//   - A file in a skill folder that is neither the skill's own (SKILL.md,
//     template.html, examples/) nor a shared copy is stale and is removed.

import { readFileSync, writeFileSync, readdirSync, statSync, existsSync, mkdirSync, rmSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildIndex, collect } from '../shared/snippets.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const shared = join(root, 'shared');
const skillsDir = join(root, '.agents', 'skills');
const checkOnly = process.argv.includes('--check');

const JUNK = new Set(['__pycache__', '.DS_Store', 'node_modules']);
const walk = (dir) =>
  readdirSync(dir).filter((name) => !JUNK.has(name)).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
const posix = (p) => p.split(sep).join('/');

const stale = [];
const problems = [];
const write = (path, data) => {
  const current = existsSync(path) ? readFileSync(path) : null;
  if (current && Buffer.compare(current, Buffer.from(data)) === 0) return;
  stale.push(relative(root, path));
  if (checkOnly) return;
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, data);
};
const remove = (path) => {
  stale.push(`${relative(root, path)} (remove)`);
  if (!checkOnly) rmSync(path);
};

// --- Snippet index (built-in only; index.mjs adds custom snippets at run time)
const snippetsDir = join(shared, 'snippets');
const found = collect([{ source: 'built-in', snippets: snippetsDir }]);
for (const p of found.problems) problems.push(relative(root, p.split(':')[0]) + p.slice(p.indexOf(':')));
const index = buildIndex(found, {
  link: (e) => e.file,
  choosing: readFileSync(join(snippetsDir, 'choosing.md'), 'utf8'),
  generatedNote:
    '<!-- Generated by scripts/sync.mjs from each snippet\'s header and choosing.md. Do not edit. -->\n\n' +
    'Built-in snippets only. Run `node <skill-dir>/index.mjs` for the full list, including custom blocks.',
  showSource: false,
});
write(join(snippetsDir, 'INDEX.md'), index);

// --- Copies into each skill ---------------------------------------------------
const START = '/* @shared-css:start (from shared/style.css; edit there, then run scripts/sync.mjs) */';
const END = '/* @shared-css:end */';
const css = readFileSync(join(shared, 'style.css'), 'utf8').trimEnd();
const block = `${START}\n${css}\n  ${END}`;
const region = /\/\* @shared-css:start[\s\S]*?\/\* @shared-css:end \*\//;
const INPUTS = new Set(['style.css', 'snippets/choosing.md']);
const OWN = (rel) => rel === 'SKILL.md' || rel === 'template.html' || rel.startsWith('examples/');

const sharedFiles = walk(shared)
  .map((p) => posix(relative(shared, p)))
  .filter((rel) => !INPUTS.has(rel));

const skills = readdirSync(skillsDir).filter((d) => existsSync(join(skillsDir, d, 'SKILL.md')));
for (const skill of skills) {
  const dir = join(skillsDir, skill);
  for (const rel of sharedFiles) {
    const data = rel === 'snippets/INDEX.md' ? index : readFileSync(join(shared, rel));
    write(join(dir, rel), data);
  }
  for (const p of walk(dir)) {
    const rel = posix(relative(dir, p));
    if (!OWN(rel) && !sharedFiles.includes(rel)) remove(p);
  }
  const pages = [join(dir, 'template.html')];
  if (existsSync(join(dir, 'examples'))) {
    pages.push(...readdirSync(join(dir, 'examples')).filter((f) => f.endsWith('.html')).map((f) => join(dir, 'examples', f)));
  }
  for (const page of pages) {
    if (!existsSync(page)) continue;
    const html = readFileSync(page, 'utf8');
    if (!region.test(html)) {
      problems.push(`${relative(root, page)}: no @shared-css markers inside its <style> block`);
      continue;
    }
    write(page, html.replace(region, () => block));
  }
}

for (const p of problems) console.error(`  FAIL ${p}`);
if (checkOnly && stale.length) {
  console.error(`out of date (run node scripts/sync.mjs):\n${stale.map((s) => `  ${s}`).join('\n')}`);
  process.exit(1);
}
if (problems.length) process.exit(1);
console.log(
  checkOnly
    ? `in sync: ${skills.join(', ')}`
    : stale.length
      ? `updated ${stale.length} file(s) in ${skills.join(', ')}`
      : `already in sync: ${skills.join(', ')}`,
);
