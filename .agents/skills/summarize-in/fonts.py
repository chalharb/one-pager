#!/usr/bin/env python3
"""Embed the site fonts into a one-pager. Python twin of fonts.mjs, for
sandboxes without Node (e.g. ChatGPT). Output is byte-for-byte the same.

    python3 fonts.py <file.html>
"""
import base64
import pathlib
import re
import sys

if len(sys.argv) != 2 or not pathlib.Path(sys.argv[1]).is_file():
    sys.exit("usage: python3 fonts.py <file.html>")

page = pathlib.Path(sys.argv[1])
fonts = pathlib.Path(__file__).resolve().parent / "fonts"
faces = [
    ("Schibsted Grotesk", "schibsted-grotesk-latin.woff2", "400 900"),
    ("Geist Mono", "geist-mono-latin.woff2", "100 900"),
]

css = "\n".join(
    f'@font-face{{font-family:"{family}";font-style:normal;font-weight:{weight};'
    f"font-display:swap;src:url(data:font/woff2;base64,"
    f'{base64.b64encode((fonts / name).read_bytes()).decode()}) format("woff2")}}'
    for family, name, weight in faces
)
block = (
    "<!-- @fonts:start (generated by fonts.mjs; do not edit) -->\n"
    f"<style>\n{css}\n</style>\n<!-- @fonts:end -->"
)

html = page.read_text(encoding="utf-8")
embedded = re.compile(r"<!-- @fonts:start[\s\S]*?<!-- @fonts:end -->")
if embedded.search(html):
    html = embedded.sub(lambda _: block, html, count=1)
elif "<!-- @fonts -->" in html:
    html = html.replace("<!-- @fonts -->", block, 1)
else:
    sys.exit(f"{page}: no <!-- @fonts --> marker found (put one just before </body>)")

page.write_text(html, encoding="utf-8")
print(f"{page}: embedded {' + '.join(f[0] for f in faces)} ({len(css) // 1024} KB)")
